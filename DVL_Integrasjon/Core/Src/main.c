void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart) {
	uint8_t newline[] = "\n\r";

	if (__HAL_UART_GET_FLAG(huart, UART_FLAG_ORE)) {
	    uint8_t errMsg[] = "Overrun error!\n";
	    HAL_UART_Transmit(&huart2, errMsg, sizeof(errMsg), 100);
	}

	if (huart->Instance == USART1) {
		if (tegn == '\n' || tegn =='\r') {
			buffer[rxIndex] = '\0';		//Null-terminer strengen
			delMelding(buffer);			//Informasjon som skal brukes videre hentes ut.
//			sendMelding(buffer);		//Send meldingen i buffer
			nullstillBuffer(buffer);	//Nullstill buffer
			rxIndex = 0;				//Nullstill indeks
		}
		else {
			if (rxIndex < BUFFER_SIZE - 1) {
				buffer[rxIndex++] = tegn;
			}
		}
	HAL_UART_Receive_DMA(&huart1,(uint8_t *)&tegn, 1);
	}
}



void sendMelding(uint8_t *melding) {
	uint8_t newline[] = "\n\r";

	HAL_UART_Transmit(&huart2, melding, BUFFER_SIZE,100);
	HAL_UART_Transmit(&huart2, newline, 2, 100);
}

void nullstillBuffer(uint8_t *buffer) {
	for (int i=0; i<BUFFER_SIZE;i++) {
		buffer[i] = '\0';
	}
}


void HAL_UART_ErrorCallback(UART_HandleTypeDef *huart) {
uint8_t feilmelding1[] = "UART error detected\n\r";
uint8_t feilmelding2[] = "Overrun error cleared\n\r";
uint8_t feilmelding3[] = "Noise error cleared\n\r";
uint8_t feilmelding4[] = "Framing error cleared\n\r";

if(huart->Instance == USART1) {							//Sjekk om det var USART1 som fikk feilen
	HAL_UART_Transmit(&huart2,feilmelding1,22,100);

	//Sjekk for spesifikke feil og håndter dem
	if(__HAL_UART_GET_FLAG(huart, UART_FLAG_ORE)) {		//Overrun error
		__HAL_UART_CLEAR_OREFLAG(huart);
		HAL_UART_Transmit(&huart2, feilmelding2, 23, 100);
	}
	if(__HAL_UART_GET_FLAG(huart, UART_FLAG_NE)) {		//Noise error
		__HAL_UART_CLEAR_NEFLAG(huart);
		HAL_UART_Transmit(&huart2, feilmelding3, sizeof(feilmelding3), 100);
	}
	if(__HAL_UART_GET_FLAG(huart, UART_FLAG_FE)) {		//Framing error
		__HAL_UART_CLEAR_FEFLAG(huart);
		HAL_UART_Transmit(&huart2, feilmelding4, sizeof(feilmelding4), 100);
	}

	//Restart mottaket etter feil
	HAL_UART_Receive_DMA(&huart1,(uint8_t *)&tegn,1);
	}
}
